fn wayland_event_len(data: &[u8]) -> Option<usize> {
    let msg_type = *data.first()?;
    let len = match msg_type {
        ipc::WEVT_BUFFER_RELEASE => 8,
        ipc::WEVT_FRAME_DONE => 12,
        ipc::WEVT_CONFIGURE_SURFACE => 16,
        ipc::WEVT_TOPLEVEL_ACTION => 16,
        ipc::WEVT_POINTER_ENTER => 16,
        ipc::WEVT_POINTER_LEAVE => 8,
        ipc::WEVT_POINTER_MOTION => 20,
        ipc::WEVT_POINTER_BUTTON => 12,
        ipc::WEVT_KEYBOARD_ENTER => 8,
        ipc::WEVT_KEYBOARD_LEAVE => 8,
        ipc::WEVT_KEYBOARD_KEY => 16,
        _ => 1,
    };
    Some(len)
}
